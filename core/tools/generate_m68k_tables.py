#!/usr/bin/env python3
"""Generate the 68000 dispatch tables from the pinned Starscream generator.

The tool compiles a temporary, instrumented copy of Gens' Main68k Star.c. The copy records which
instruction routine each of the 65536 opcodes uses and the generator parameters that routine was
emitted with. The pinned source is never modified. The C core implements every routine family
from those parameters, so the decode itself is taken from the original generator.
"""

import argparse
import os
from pathlib import Path
import re
import shlex
import subprocess
import sys
import tempfile

OPTIONS = ["-quiet", "-hog", "-name", "main68k_"]
FIELDS = ("eamode", "destmode", "size", "sizedef", "reg", "cc", "dr", "ir", "qv")


def instrument(source):
    code = re.sub(r"/\*.*?\*/", "", source, flags=re.S)
    code = re.sub(r"//[^\n]*", "", code)
    names = sorted(set(re.findall(r",\s*(i_\w+)\s*\)", code)))
    if not names:
        raise ValueError("no instruction routines found")
    marker = "#include <stdarg.h>\n"
    idef = "\tcease_decode = test(n, mask, op);\n"
    opened = "\tcodefile = fopen(codefilename, \"w\");\n"
    closing = "\tfclose(codefile);\n\treturn 0;\n}\n"
    for text in (marker, idef, opened, closing):
        if source.count(text) != 1:
            raise ValueError(f"expected unique generator marker {text!r}")
    source = source.replace(marker, marker +
                            "static FILE *tablefile;\n"
                            "static const char *procname(void (*p)(void));\n")
    source = source.replace(idef, idef +
                            "\tif(cease_decode == 1) fprintf(tablefile, "
                            "\"R %d %s %d %d %d %d %d %d %d %d %d\\n\", n, procname(proc), "
                            "(int)main_eamode, (int)main_destmode, main_size, sizedef, main_reg, "
                            "main_cc, main_dr, main_ir, main_qv);\n")
    source = source.replace(opened, opened +
                            "\ttablefile = fopen(getenv(\"STAR_TABLE\"), \"w\");\n"
                            "\tif(!tablefile) return 1;\n")
    source = source.replace(closing,
                            "\tfor(i = 0; i < 0x10000; i++) fprintf(tablefile, \"T %d %d\\n\", "
                            "i, rproc[i]);\n\tfclose(tablefile);\n" + closing)
    source += "\nstatic const char *procname(void (*p)(void)) {\n"
    for name in names:
        source += f"\tif(p == {name}) return \"{name}\";\n"
    source += "\treturn \"?\";\n}\n"
    return source


def run_generator(star_source, compiler):
    with tempfile.TemporaryDirectory() as directory:
        work = Path(directory)
        (work / "star.c").write_text(instrument(star_source), encoding="latin-1", newline="\n")
        executable = work / ("star.exe" if os.name == "nt" else "star")
        subprocess.run(shlex.split(compiler, posix=os.name != "nt") +
                       ["-O1", "-w", str(work / "star.c"), "-o", str(executable)], check=True)
        environment = dict(os.environ, STAR_TABLE=str(work / "table.txt"))
        subprocess.run([str(executable), str(work / "main68k.asm")] + OPTIONS, check=True,
                       cwd=work, env=environment)
        return (work / "table.txt").read_text(encoding="ascii")


def parse(table):
    routines, mapping = {}, [None] * 0x10000
    for line in table.splitlines():
        parts = line.split()
        if parts[0] == "R":
            opcode, name = int(parts[1]), parts[2]
            if name == "?":
                raise ValueError(f"unknown routine for opcode {opcode:04x}")
            routines[opcode] = (name, tuple(int(value) for value in parts[3:]))
        elif parts[0] == "T":
            mapping[int(parts[1])] = int(parts[2])
    if None in mapping:
        raise ValueError("incomplete opcode mapping")
    illegal = [n for n, (name, _) in routines.items() if name == "i_illegal"]
    if not illegal:
        raise ValueError("no illegal-instruction routine")
    # Unassigned opcodes use r_illegal, the label at the start of the first i_illegal routine.
    mapping = [min(illegal) if value == -1 else value for value in mapping]
    for value in mapping:
        if value not in routines:
            raise ValueError(f"opcode maps to unknown routine {value:04x}")
    return routines, mapping


def generate(routines, mapping):
    names = sorted({name for name, _ in routines.values()})
    order = sorted(routines)
    index = {opcode: position for position, opcode in enumerate(order)}
    lines = ["/* Generated by tools/generate_m68k_tables.py from the pinned Starscream Star.c. */\n",
             '#include "gens_m68k_tables.h"\n\n',
             f"const GensM68kRoutine gens_m68k_routines[{len(order)}] = {{\n"]
    for opcode in order:
        name, values = routines[opcode]
        fields = ", ".join(str(value) for value in values)
        lines.append(f"    /* {opcode:04X} */ {{GENS_M68K_{name[2:].upper()}, {fields}}},\n")
    lines.append("};\n\n")
    runs, last, count = [], None, 0
    for opcode in range(0x10000):
        value = index[mapping[opcode]]
        if value == last and count < 0xffff:
            count += 1
        else:
            if last is not None:
                runs.append((last, count))
            last, count = value, 1
    runs.append((last, count))
    lines.append(f"const GensM68kRun gens_m68k_runs[{len(runs)}] = {{\n")
    for start in range(0, len(runs), 6):
        lines.append("    " + " ".join(f"{{{r}, {c}}}," for r, c in runs[start:start + 6]) + "\n")
    lines.append("};\n")
    header = (
        "/* Generated by tools/generate_m68k_tables.py. */\n"
        "#ifndef CHIMERA_GENS_M68K_TABLES_H\n#define CHIMERA_GENS_M68K_TABLES_H\n\n"
        "#include <stdint.h>\n\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n"
        "enum GensM68kHandler {\n" +
        ",\n".join(f"    GENS_M68K_{name[2:].upper()}" for name in names) + "\n};\n\n"
        "enum GensM68kEaMode {\n"
        "    GENS_M68K_DREG, GENS_M68K_AREG, GENS_M68K_AIND, GENS_M68K_AINC, GENS_M68K_ADEC,\n"
        "    GENS_M68K_ADSP, GENS_M68K_AXDP, GENS_M68K_ABSW, GENS_M68K_ABSL, GENS_M68K_PCDP,\n"
        "    GENS_M68K_PCXD, GENS_M68K_IMMD\n};\n\n"
        "/* Generator parameters the routine was emitted with. */\n"
        "typedef struct GensM68kRoutine {\n"
        "    uint8_t handler;\n"
        "    int8_t " + ", ".join(FIELDS) + ";\n"
        "} GensM68kRoutine;\n\n"
        "typedef struct GensM68kRun {\n    uint16_t routine, count;\n} GensM68kRun;\n\n"
        f"#define GENS_M68K_ROUTINE_COUNT {len(order)}u\n"
        f"#define GENS_M68K_RUN_COUNT {len(runs)}u\n\n"
        "extern const GensM68kRoutine gens_m68k_routines[GENS_M68K_ROUTINE_COUNT];\n"
        "extern const GensM68kRun gens_m68k_runs[GENS_M68K_RUN_COUNT];\n\n"
        "#ifdef __cplusplus\n}\n#endif\n\n#endif\n"
    )
    return "".join(lines), header


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("star", type=Path, help="pinned Starscream/Main68k/Star.c")
    parser.add_argument("directory", type=Path)
    parser.add_argument("--cc", default=os.environ.get("CC", "cc"))
    args = parser.parse_args()
    try:
        table = run_generator(args.star.read_text(encoding="latin-1"), args.cc)
        source, header = generate(*parse(table))
        (args.directory / "gens_m68k_tables.c").write_text(source, newline="\n")
        (args.directory / "gens_m68k_tables.h").write_text(header, newline="\n")
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        parser.exit(1, f"68000 table generation failed: {error}\n")


if __name__ == "__main__":
    sys.exit(main())
